"""失败测甲：同号再灌后，正式入栏（现行）行数不得再涨。

夹具：首装 dup-a 入栏、dup-b 坏点；再灌同号两条（读数已改，若漏幂等会双双入栏）。
- 切流账册：再灌整票拒绝，现行不涨，账册能回看拒因。
- 双写归档：再灌现行不涨，旧报文落只读归档，现行条数与归档旧行分开可读。
"""
from app.modules import 报文键幂等 as 幂等
from app.services import 装载, 目录, 夹具


def _现行():
    概 = 目录.概览()
    return {"观测报文": 概["观测报文"], "在栏": 概["在栏"], "坏点": 概["坏点"]}


def test_切流账册_同号再入现行不涨():
    首 = 装载.装一批(夹具.读取("同号首装样例"))
    assert 首["入栏"] == 1 and 首["坏点"] == 1 and 首["驳回"] == 0
    前 = _现行()
    再 = 装载.装一批(夹具.读取("同号再灌样例"))
    assert 再["入流"] == 0 and 再["入栏"] == 0 and 再["坏点"] == 0
    assert 再["驳回"] == 2
    assert _现行() == 前, "同号再灌后现行行数不得涨"
    # 账册能回看拒因
    裁 = 幂等.裁决查("dup-a")
    assert 裁 and 裁["账册"]["再灌次数"] == 1
    assert 裁["账册"]["最近裁决"] == "驳回-同号"
    assert "同号" in 裁["账册"]["拒因"]
    # 首条读数不被回刷
    行 = [r for r in 目录.报文列表() if r["报文编号"] == "dup-a"]
    assert len(行) == 1 and 行[0]["读数"] == 30.0


def test_双写归档_同号再入现行不涨且归档留旧():
    目录.改栏规({"幂等策略": "双写归档"})
    首 = 装载.装一批(夹具.读取("同号首装样例"))
    assert 首["入栏"] == 1 and 首["坏点"] == 1
    前 = _现行()
    再 = 装载.装一批(夹具.读取("同号再灌样例"))
    assert 再["入流"] == 0 and 再["入栏"] == 0 and 再["坏点"] == 0
    assert 再["归档"] == 2
    assert _现行() == 前
    # 归档留旧：回刷的两条旧报文进只读归档
    汇 = 幂等.账册汇总()
    assert 汇["归档同号"] == 2
    归 = 幂等.归档列表()
    assert len(归) == 2
    assert sorted(r["读数"] for r in 归) == [40.0, 55.0]
    # 现行条数与归档有无旧行分开可读
    裁 = 幂等.裁决查("dup-b")
    assert 裁["现行"] is not None and 裁["现行"]["读数"] == 120.0
    assert len(裁["归档"]) == 1 and 裁["归档"][0]["读数"] == 40.0
